class I18nManager(QObject):
    """国际化多语言管理器（单例）"""

    language_changed = pyqtSignal(str)
    _instance = None

    def __new__(cls):
        if cls._instance is None:
            cls._instance = super().__new__(cls)
            cls._instance._initialized = False
        return cls._instance

    def __init__(self):
        if getattr(self, "_initialized", False):
            return
        super().__init__()
        self._initialized = True
        self._current_lang = Settings().language or "zh"
        if self._current_lang not in SUPPORTED_LANGUAGES:
            self._current_lang = "zh"

    @property
    def current_language(self) -> str:
        return self._current_lang

    def set_language(self, lang: str):
        if lang not in SUPPORTED_LANGUAGES:
            return
        if self._current_lang != lang:
            self._current_lang = lang
            Settings().language = lang
            self.language_changed.emit(lang)

    def tr(self, key: str, default: str = None) -> str:
        lang_dict = TRANSLATIONS.get(self._current_lang, TRANSLATIONS["zh"])
        if key in lang_dict:
            return lang_dict[key]
        zh_dict = TRANSLATIONS.get("zh", {})
        if key in zh_dict:
            return zh_dict[key]
        return default if default is not None else key


def tr(key: str, default: str = None) -> str:
    """快捷获取国际化文本"""
    return I18nManager().tr(key, default)
